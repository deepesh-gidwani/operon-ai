"""Markdown renderer for downloadable reports."""

from __future__ import annotations

from .models import Report


def render_markdown(report: Report) -> str:
    lines = [
        "# Operon AI — Operations Intelligence Report",
        "",
        f"**Run:** {report.run_id}  ",
        f"**Objective:** {report.objective}  ",
        f"**Model:** {report.model}  ",
        f"**Status:** {report.status}",
        "",
        "## Execution plan",
        "",
        f"{report.plan.rationale if report.plan else '_No plan recorded._'}",
        "",
        "## KPIs",
        "",
    ]
    for kpi in report.kpis:
        detail = f" ({kpi.detail})" if kpi.detail else ""
        lines.append(f"- **{kpi.label}:** {kpi.value}{detail}")
    lines += ["", "## Chart", "", f"{report.chart.title} ({report.chart.kind} chart)", ""]
    for row in report.chart.data[:20]:
        pairs = ", ".join(f"{k}={v}" for k, v in row.items())
        lines.append(f"- {pairs}")
    if report.metrics:
        lines += ["", "## Key metrics (deterministic)", ""]
        for m in report.metrics[:12]:
            lines.append(f"- **{m.id}:** {m.detail}")
    lines += ["", "## Data brief", "", report.profile.data_brief or "_Unavailable._", ""]
    lines += ["## Insights", ""]
    for i, insight in enumerate(report.insights, start=1):
        lines.append(f"### {i}. {insight.title}")
        lines.append("")
        lines.append(insight.body)
        lines.append("")
        for ev in insight.evidence:
            lines.append(f"- Evidence: {ev}")
        if insight.metric_refs:
            lines.append(f"- Metrics: {', '.join(insight.metric_refs)}")
        lines.append("")
    if not report.insights:
        lines += ["_No insights generated._", ""]
    lines += ["## Recommended actions", ""]
    for action in report.actions:
        lines.append(f"### {action.rank}. {action.title} (effort: {action.effort})")
        lines.append("")
        lines.append(action.body)
        lines.append("")
        if action.expected_impact:
            lines.append(f"Expected impact: {action.expected_impact}")
            lines.append("")
        if action.evidence_refs:
            lines.append(f"Evidence: {', '.join(action.evidence_refs)}")
            lines.append("")
        if action.uncertainty:
            lines.append(f"Uncertainty: {action.uncertainty}")
            lines.append("")
    if not report.actions:
        lines += ["_No actions generated._", ""]
    if report.warnings:
        lines += ["## Warnings", ""]
        for w in report.warnings:
            lines.append(f"- {w}")
        lines.append("")
    lines.append("_Generated by Operon AI — Intelligence, Orchestrated._")
    return "\n".join(lines) + "\n"
